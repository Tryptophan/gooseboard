export type ItemType = 'note' | 'stroke' | 'file' | 'folder' | 'link'

export interface ItemBase {
  id: string
  type: ItemType
  x: number
  y: number
  w: number
  h: number
  /** radians */
  rot: number
  z: number
  /** id of the containing folder, or null for the board */
  parent: string | null
}

/** Note text lives in a Y.XmlFragment under `content` (not part of the plain item). */
export interface NoteItem extends ItemBase {
  type: 'note'
  color: string
  title?: string
  /** the note's base text size, from before sizes were set per run of text (see TextSize) */
  fontSize?: NoteFontSize
}

export type NoteFontSize = 's' | 'm' | 'l' | 'xl'
/** body text size in px on the board; the note window scales them up a little */
export const NOTE_FONT_SIZES: Record<NoteFontSize, number> = { s: 12, m: 15, l: 19, xl: 25 }

export interface StrokeItem extends ItemBase {
  type: 'stroke'
  /** flat [x, y, pressure, ...] relative to the item origin, in the original ow x oh box */
  points: number[]
  ow: number
  oh: number
  color: string
  size: number
  opacity: number
}

export interface FileItem extends ItemBase {
  type: 'file'
  name: string
  size: number
  mime: string
  /** profile id of the person whose disk serves the bytes */
  owner: string
  ownerName: string
  /** key into the owner's local source table */
  key: string
  /** small data URL generated by the owner */
  thumb?: string
  /** content hash (lib/hash), filled in by the owner after adding; lets any holder serve it */
  hash?: string
  /** natural pixel size of an image or video; with it, the item shows bare (no card) at this aspect */
  iw?: number
  ih?: number
}

export interface FolderItem extends ItemBase {
  type: 'folder'
  name: string
  /** virtual: groups board items. disk: a real directory served by `owner`. */
  mode: 'virtual' | 'disk'
  owner: string
  ownerName: string
  key?: string
  color: string
}

export interface LinkItem extends ItemBase {
  type: 'link'
  url: string
  title?: string
  /** show a plain card even when the link has an embed (lib/embed) */
  card?: boolean
}

export type Item = NoteItem | StrokeItem | FileItem | FolderItem | LinkItem

export const DEFAULT_SIZE: Record<ItemType, { w: number; h: number }> = {
  note: { w: 240, h: 200 },
  stroke: { w: 10, h: 10 },
  file: { w: 200, h: 176 },
  folder: { w: 180, h: 132 },
  link: { w: 260, h: 84 },
}

export const NOTE_COLORS = ['#fff3a3', '#ffd0a6', '#ffc2cf', '#cde8ff', '#c9f0c8', '#e3d4ff']
export const FOLDER_COLORS = ['#f2c14e', '#7aa7ff', '#7bd3a0', '#f59fb7', '#b9a1ff', '#9aa5b1']
export const PEN_COLORS = ['#e5484d', '#f76b15', '#d9a400', '#30a46c', '#3e63dd', '#8e4ec6', '#ffffff', '#1f2328']

/** Awareness payload for a connected person. */
export interface PresenceUser {
  id: string
  name: string
  color: string
}

export interface Presence {
  user: PresenceUser
  cursor: { x: number; y: number } | null
  /** camera centre + zoom, used by "follow" */
  view: { cx: number; cy: number; z: number } | null
  /** in-progress stroke, downsampled, for live preview */
  draft: { points: number[]; color: string; size: number; opacity: number } | null
}
